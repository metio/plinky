describe("the fingering chooser, exactly as pinned", () => {
    it("fingers a line the same as ever", () => {
        for (const pin of [PINNED.line1, PINNED.line2, PINNED.line3]) {
            expect(fingerLine([...pin.line], "right")).toEqual(pin.right);
            expect(fingerLine([...pin.line], "left", 10)).toEqual(pin.left);
        }
    });

    it("fingers a sequence of positions the same as ever", () => {
        for (const pin of [PINNED.pos1, PINNED.pos2, PINNED.pos3]) {
            const positions = pin.positions.map((position) => [...position]);
            expect(fingerPositions(positions, "right")).toEqual(pin.right);
            expect(fingerPositions(positions, "left", 11, [...pin.gaps])).toEqual(pin.left);
        }
    });
});
